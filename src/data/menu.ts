export function getProductName(product: ProductItem, isAr: boolean): string {
  if (isAr && product.name_ar && product.name_ar.trim().length > 0) {
    return product.name_ar;
  }
  return product.name_en || product.name;
}

export function getProductDescription(product: ProductItem, isAr: boolean): string {
  if (isAr && product.description_ar && product.description_ar.trim().length > 0) {
    return product.description_ar;
  }
  return product.description_en || product.description || '';
}

export function getProductIngredients(product: ProductItem, isAr: boolean): string[] {
  if (isAr && product.ingredients_ar && product.ingredients_ar.length > 0) {
    return product.ingredients_ar;
  }
  return product.ingredients_en || product.ingredients || [];
}

export function getOptionSizeName(size: string | undefined, isAr: boolean): string {
  if (!size) return '';
  if (size === 'Double') return isAr ? 'دابل' : 'Double';
  if (size === 'Triple') return isAr ? 'تريبل' : 'Triple';
  if (size === 'Quad') return isAr ? 'كواد' : 'Quad';
  if (size === 'Large') return isAr ? 'كبير' : 'Large';
  if (size === 'X-Large') return isAr ? 'عائلي' : 'X-Large';
  return size;
}

export function getCategoryDisplayName(cat: string, isAr: boolean): string {
  if (!isAr) {
    if (cat === 'Smash Burgers') return 'Beef Smash Burgers';
    return cat;
  }
  switch (cat) {
    case 'Exclusive':
      return '⭐ حصري';
    case 'Offers':
    case 'Online Only Offers':
      return '🔥 العروض والبوكسات';
    case 'Smash Burgers':
      return '🍔 برجر اللحم السماش';
    case 'Chicken Collection':
      return '🍗 ساندوتشات الدجاج الكريسبي';
    case 'Salads':
      return '🥗 السلطات الطازجة';
    case 'Appetizers':
      return '🍟 المقبلات والتشاوس فرايز';
    case 'Sauces':
      return '🌶️ صوصات بلاك برجر';
    case 'Additions':
      return '🧀 إضافات وتوبينج';
    default:
      return cat;
  }
}

